package ru.rooyzee.elytrixparadise.sphere;

public enum SphereState {
    INTACT,           // Сфера подвешена на цепях, активна (синяя керамика), гравитация включена
    FALLING,          // Анимация плавного падения сферы вниз на алтарь
    FALLEN_MINING,    // Сфера на алтаре, игроки добывают киркой (6 взрывов до истощения)
    ASCENDING,        // Сфера плавно поднимается обратно наверх
    RESTORING_CHAINS, // Восстановление цепей
    COOLDOWN          // Перезарядка (3 часа, серая керамика, неактивна)
}
